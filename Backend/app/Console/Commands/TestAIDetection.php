<?php

namespace App\Console\Commands;

use Illuminate\Console\Command;
use App\Services\OpenAIService;

class TestAIDetection extends Command
{
    protected $signature = 'ai:test-detection';
    protected $description = 'Test AI detection service';

    protected $detectionService;

    public function __construct(OpenAIService $detectionService)
    {
        parent::__construct();
        $this->detectionService = $detectionService;
    }

    public function handle()
    {
        $this->info('🧪 Testing AI Detection...');
        $this->newLine();
        
        $testText = "This is a test text generated by AI. It demonstrates how the tool can detect and humanize AI-generated content effectively. The algorithm analyzes patterns, repetition, and sentence structure to determine if text was written by AI.";
        
        $this->info('📝 Testing text:');
        $this->line($testText);
        $this->newLine();
        
        $this->info('⏳ Analyzing...');
        $result = $this->detectionService->detectAIContent($testText);
        
        $this->newLine();
        $this->info('📊 Results:');
        $this->line('─────────────────────────────────');
        
        if ($result) {
            // Check if key is 'score' or 'ai_score'
            $score = $result['score'] ?? $result['ai_score'] ?? 0;
            $confidence = $result['confidence'] ?? 0;
            $method = $result['method'] ?? 'unknown';
            $indicators = $result['indicators'] ?? [];
            
            $this->info('AI Score: ' . ($score * 100) . '%');
            $this->info('Confidence: ' . ($confidence * 100) . '%');
            $this->info('Method: ' . $method);
            $this->info('Indicators:');
            
            if (is_array($indicators)) {
                foreach ($indicators as $indicator) {
                    if (is_string($indicator)) {
                        $this->line('  • ' . $indicator);
                    } elseif (is_array($indicator)) {
                        $this->line('  • ' . implode(', ', $indicator));
                    }
                }
            } else {
                $this->line('  • ' . $indicators);
            }
        } else {
            $this->error('❌ No result returned from API');
        }
        
        $this->line('─────────────────────────────────');
        $this->newLine();
        $this->info('✅ Detection test completed!');
        
        return 0;
    }
}
