<?php

namespace App\Console\Commands;

use Illuminate\Console\Command;
use App\Services\TextHumanizerService;

class TestAIHumanization extends Command
{
    /**
     * The name and signature of the console command.
     *
     * @var string
     */
    protected $signature = 'ai:test-humanization';

    /**
     * The console command description.
     *
     * @var string
     */
    protected $description = 'Test AI humanization service';

    /**
     * The humanizer service instance.
     *
     * @var \App\Services\TextHumanizerService
     */
    protected $humanizerService;

    /**
     * Create a new command instance.
     *
     * @param \App\Services\TextHumanizerService $humanizerService
     * @return void
     */
    public function __construct(TextHumanizerService $humanizerService)
    {
        parent::__construct();
        $this->humanizerService = $humanizerService;
    }

    /**
     * Execute the console command.
     *
     * @return int
     */
    public function handle()
    {
        // Display header
        $this->info('🧪 Testing AI Humanization...');
        $this->newLine();
        
        // Test text
        $testText = "This is a test text generated by AI. It demonstrates how the tool can detect and humanize AI-generated content effectively. The algorithm analyzes patterns, repetition, and sentence structure to determine if text was written by AI.";
        
        // Show original text
        $this->info('📝 Original text:');
        $this->line($testText);
        $this->newLine();
        
        // Process humanization
        $this->info('⏳ Humanizing...');
        $result = $this->humanizerService->humanize($testText, 'casual');
        
        // Display results
        $this->newLine();
        $this->info('📊 Humanized result:');
        $this->line('─────────────────────────────────');
        
        if ($result && $result !== $testText) {
            $this->line($result);
            $this->newLine();
            
            // Show comparison stats
            $originalWords = str_word_count($testText);
            $humanizedWords = str_word_count($result);
            $wordDifference = $humanizedWords - $originalWords;
            
            $this->info('📈 Comparison:');
            $this->line('  • Original words: ' . $originalWords);
            $this->line('  • Humanized words: ' . $humanizedWords);
            $this->line('  • Difference: ' . ($wordDifference > 0 ? '+' : '') . $wordDifference . ' words');
            
        } elseif ($result === $testText) {
            $this->warn('⚠️ Humanized text is identical to original (fallback used)');
            $this->line($result);
        } else {
            $this->error('❌ No result returned from API');
        }
        
        $this->line('─────────────────────────────────');
        $this->newLine();
        $this->info('✅ Humanization test completed!');
        
        return 0;
    }
}